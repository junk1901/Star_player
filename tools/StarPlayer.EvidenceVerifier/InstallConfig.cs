using System.Runtime.Versioning;
using StarPlayer.SimHarness.Evidence;
using static StarPlayer.SimHarness.Evidence.Schema;

namespace StarPlayer.EvidenceVerifier;

/// <summary>An approved executable or library: its canonical absolute path and the SHA-256 of its bytes.</summary>
public sealed record ToolPin(string Path, string Sha256);

/// <summary>
/// G4-T1: the OWNER-managed installation settings the official verifier reads its trust anchor from (§16 T1: never a path from the evidence or a CLI evidence argument), plus the roots and the execution-chain
/// pins of G4-T2..T8. This is NOT a B1-T00 contract schema: its format and location are a B-4 / G4 operational proposal that needs OWNER norm decisions N-5 / N-6 / N-7 before any official use, and every value
/// in it is an OWNER value (nothing here is generated by the verifier).
/// </summary>
public sealed record InstallConfig(
    string AnchorPath, string BuildRoot, string ArchiveRoot, string WorkRoot, ToolPin Dotnet, ToolPin Git, IReadOnlyList<ToolPin> ExecutionPins, IReadOnlyList<string> StartupForbiddenPrefixes,
    IReadOnlyList<string> AllowedDynamicAssemblies, IReadOnlyList<string> UnpinnedOutputFiles, byte[] Raw, string RawSha256);

[SupportedOSPlatform("windows")]
public static class InstallConfigReader
{
    public const string Format = "starplayer-verifier-install-config-v1";

    /// <summary>
    /// G4-ENV-01 (OWNER 2026-10-31): <c>startup_forbidden_prefixes</c> must name exactly this token. <c>VSTEST_CONSOLE_PATH</c> makes <c>dotnet test</c> run another test runner, and the other
    /// <c>VSTEST_*</c> variables change its waits, logs and post-processing; this prefix makes the start check refuse them and the Test Profile child drop them.
    /// </summary>
    public const string RequiredStartupPrefix = "VSTEST_";

    /// <summary>The one fixed location (no CLI or evidence input can move it): <c>%ProgramData%\StarPlayer\EvidenceVerifier\install-config.json</c>.</summary>
    public static string DefaultPath => System.IO.Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), "StarPlayer", "EvidenceVerifier", "install-config.json");

    private static readonly Shape AbsPath = Str(v => WindowsLocalAbsPath.Syntax(v) is null, "WINDOWS_LOCAL_ABS_PATH");

    private static readonly Shape Pin = Obj(("path", AbsPath), ("raw_sha256", H));

    private static Shape SortedUnique(Shape item) => (n, p) =>
    {
        Arr(item)(n, p);
        var v = Items(n).Select(Text).ToList();
        for (var i = 1; i < v.Count; i++)
            if (string.CompareOrdinal(v[i - 1], v[i]) >= 0)
                throw new EvidenceException(new EvidenceError(EvidenceCodes.SchemaInvalid, "Schema.order", $"{p}/{i}", Stage, "ordinal 오름차순·중복 금지입니다."));
    };

    public static readonly Shape ConfigShape = Obj(
        ("format", Const(Format)), ("anchor_path", AbsPath), ("build_root", AbsPath), ("archive_root", AbsPath), ("work_root", AbsPath), ("dotnet", Pin), ("git", Pin),
        ("execution_pins", Arr(Pin)), ("startup_forbidden_prefixes", SortedUnique(Pattern("^[A-Za-z][A-Za-z0-9_]{0,63}$", "PREFIX"))), ("allowed_dynamic_assemblies", SortedUnique(Text1)),
        ("unpinned_output_files", SortedUnique(RelPath)));

    private static EvidenceException Untrusted(string cause, string message) => EvidenceCodes.Fail(EvidenceCodes.ApprovalMismatch, cause, "", "install_config", message);

    /// <summary>A canonical path with no reparse point on the way (the same check as the registry database path, NSC-5).</summary>
    private static string Canonical(string v, string field)
    {
        try
        {
            return WindowsLocalAbsPath.Resolve(v);
        }
        catch (EvidenceException e)
        {
            throw Untrusted("Trust.install_config_path", $"{field}: {e.Error.Message}");
        }
    }

    /// <summary>
    /// Reads the settings ONCE: the file has a canonical path with no reparse point, the process is not elevated, the file and its parents are TCB-only (NSC-4 B, the anchor's rule), and the same bytes are
    /// hashed and strictly parsed. The start prefixes name <see cref="RequiredStartupPrefix"/> exactly (G4-ENV-01). Every path in it is canonical and reparse-free; the file and the anchor lie outside the build, archive and work roots. Any failure is <c>Evidence.approval_mismatch</c>.
    /// <paramref name="acl"/> / <paramref name="elevated"/> are seams for tests; production uses the real Windows checks.
    /// </summary>
    public static InstallConfig Read(string path, Func<string, string?>? acl = null, Func<bool>? elevated = null)
    {
        if (!File.Exists(path))
            throw Untrusted("Trust.install_config_missing", $"검증기 설치 설정이 없습니다: '{path}'.");
        var full = Canonical(path, "설치 설정 경로");
        if ((elevated ?? AnchorAcl.Elevated)())
            throw Untrusted("Trust.install_config_untrusted", "검증기가 관리자 권한(Elevated)으로 실행되었습니다(NSC-4).");
        if ((acl ?? AnchorAcl.CheckPath)(full) is { } why)
            throw Untrusted("Trust.install_config_untrusted", $"설치 설정 ACL이 TCB 전용이 아닙니다(NSC-4 B): {why}");
        byte[] raw;
        using (var s = new FileStream(full, FileMode.Open, FileAccess.Read, FileShare.Read))
        {
            using var m = new MemoryStream();
            s.CopyTo(m);
            raw = m.ToArray();
        }

        var o = ApprovalFormats.Read(ConfigShape, raw);
        var prefixes = Items(o["startup_forbidden_prefixes"]).Select(Text).ToList();
        if (!prefixes.Contains(RequiredStartupPrefix, StringComparer.Ordinal) || prefixes.Any(p => p != RequiredStartupPrefix && string.Equals(p, RequiredStartupPrefix, StringComparison.OrdinalIgnoreCase)))
            throw Untrusted("Trust.install_config_policy", $"startup_forbidden_prefixes에 필수 접두사 '{RequiredStartupPrefix}'가 정확한 표기로 있어야 합니다(G4-ENV-01, 다른 표기·개별 변수 이름은 대신하지 못함).");
        ToolPin P(JNode n, string field) => new(Canonical(Text(((JObject)n)["path"]), field), Text(((JObject)n)["raw_sha256"]));
        var roots = new[] { "build_root", "archive_root", "work_root" }.ToDictionary(k => k, k => Canonical(Text(o[k]), k));
        var anchor = Canonical(Text(o["anchor_path"]), "anchor_path");
        foreach (var (name, root) in roots)
            foreach (var (what, file) in new[] { ("설치 설정", full), ("앵커", anchor) })
                if (file.StartsWith(root.TrimEnd('\\') + "\\", StringComparison.OrdinalIgnoreCase))
                    throw Untrusted("Trust.install_config_untrusted", $"{what}이 {name} 안에 있습니다: '{root}'.");
        return new InstallConfig(anchor, roots["build_root"], roots["archive_root"], roots["work_root"], P(o["dotnet"], "dotnet"), P(o["git"], "git"),
            Items(o["execution_pins"]).Select((n, i) => P(n, $"execution_pins/{i}")).ToList(), prefixes,
            Items(o["allowed_dynamic_assemblies"]).Select(Text).ToList(), Items(o["unpinned_output_files"]).Select(Text).ToList(), raw, Archive.Sha(raw));
    }
}
