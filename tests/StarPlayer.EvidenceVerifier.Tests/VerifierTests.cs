        Assert.Equal(body, Framing.Read(s));
        var big = new MemoryStream([0x7F, 0xFF, 0xFF, 0xFF]);
        Assert.Equal(EvidenceCodes.ApprovalMismatch, Assert.Throws<EvidenceException>(() => Framing.Read(big)).Error.Code);
    }

