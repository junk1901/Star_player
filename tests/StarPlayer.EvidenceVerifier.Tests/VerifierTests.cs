    [Fact]
    public void Minor01_access_check_matrix_and_fail_fast_on_a_failed_revert()
    {
        var ok = new AccessCheckResult(true, true, true, true, 0x00120003, true);
        Assert.Null(PipeSecurity.CheckAccess(ok));
        Assert.NotNull(PipeSecurity.CheckAccess(ok with { AccessCheckReturned = false, GrantedAccess = 0x7FFFFFFF }));   // FALSE return: GrantedAccess never read
        Assert.NotNull(PipeSecurity.CheckAccess(ok with { AccessStatus = false }));
        Assert.NotNull(PipeSecurity.CheckAccess(ok with { GrantedAccess = 0x00120003 | 0x4 }));                          // FILE_CREATE_PIPE_INSTANCE
        Assert.NotNull(PipeSecurity.CheckAccess(ok with { ImpersonateSelf = false }));
        Assert.NotNull(PipeSecurity.CheckAccess(ok with { OpenThreadToken = false }));
        var fatal = new List<string>();
        var original = PipeSecurity.FailFast;
        PipeSecurity.FailFast = fatal.Add;
        try
        {
            PipeSecurity.CheckAccess(ok with { RevertToSelf = false });
        }
        finally
        {
            PipeSecurity.FailFast = original;
        }

        Assert.Single(fatal);
    }
