public sealed class VerifierTests(TestOnlyWorld w) : IClassFixture<TestOnlyWorld>
{
    private static EvidenceError Refused(Action a) => Assert.Throws<EvidenceException>(a).Error;

    [Fact]
    public void The_dominance_evidence_verifies_end_to_end_as_test_only_and_its_a_plus_is_the_payload_hash()
    {
        var v = Verifier.VerifyFamily(w.DominanceRequest());
        Assert.True(v.TestOnly);
        Assert.Equal(48, v.PzlUnits.Count);
        Assert.Equal(EvidenceHash.APlus(EvidenceHash.DominancePrefix, v.Payload.Canonical), v.Payload.Hash);
        Assert.Equal(EvidenceHash.Dominance(w.DominanceDocument, v.PzlUnits).Hash, v.Payload.Hash);
        Assert.False(OfficialApprovals.Current.ExecutionPathReady);                      // N21: Current untouched
        // §19: this world's 48 cells (seed base TestOnlyWorld.DominanceSeedBase, 2 games each) give a PASS gate, which v1 certifies (B1 T11 R3 positive Phase path). The refusal of NOT_EVALUATED /
        // INCOMPLETE is the certification table's own test (CertificationAndEnvironmentTests).
        Assert.Equal(("PASS", (string?)null), (Schema.Text(JEditT.Get(v.Document, "/aggregate_evaluation/gate/status")), v.Ineligible?.Code));
    }

    /// <summary>One-off freeze of the TEST_ONLY Dominance inputs for the independent Golden (runs only with B1_GOLDEN_EXPORT set; the committed fixtures are never regenerated by a normal run).</summary>
    [Fact]
    public void Export_the_dominance_golden_inputs_when_asked()
    {
        if (Environment.GetEnvironmentVariable("B1_GOLDEN_EXPORT") is not { Length: > 0 } dir)
            return;
        var v = Verifier.VerifyFamily(w.DominanceRequest());
        Directory.CreateDirectory(Path.Combine(dir, "dom"));
        File.WriteAllBytes(Path.Combine(dir, "dom", "document.json"), Jcs.Bytes(v.Document));
        for (var i = 0; i < v.PzlUnits.Count; i++)
            File.WriteAllBytes(Path.Combine(dir, "dom", $"unit-{i:D2}.json"), Jcs.Bytes(v.PzlUnits[i]));
    }

    [Fact]
    public void A_real_engine_calibration_verifies_end_to_end_and_its_seeds_exhausted_gate_is_not_certifiable_without_the_allowance()
    {
        var (reference, doc) = w.ProduceFamily(w.Calibration, "clause-cal-test", "calibration-result.json");
        var v = Verifier.VerifyFamily(w.FamilyRequest("fc3-cal", reference));
        Assert.Equal(4, v.PzlUnits.Count);
        Assert.Equal(EvidenceHash.Family(doc, v.PzlUnits, null).Hash, v.Payload.Hash);
        Assert.All(w.Calibration.Units, u => Assert.Equal(StopReason.SeedsExhausted, u.Run.Stop!.Reason));
        Assert.Equal("INSUFFICIENT_SAMPLE", Schema.Text(JEditT.Get(doc, "/aggregate_evaluation/status")));
        Assert.Equal(EvidenceCodes.NotCertifiable, v.Ineligible?.Code);                   // §19: the record's allowance is false
        if (Environment.GetEnvironmentVariable("B1_GOLDEN_EXPORT") is { Length: > 0 } dir)
        {
            Directory.CreateDirectory(Path.Combine(dir, "cal"));
            File.WriteAllBytes(Path.Combine(dir, "cal", "document.json"), Jcs.Bytes(v.Document));
            for (var i = 0; i < v.PzlUnits.Count; i++)
                File.WriteAllBytes(Path.Combine(dir, "cal", $"unit-{i:D2}.json"), Jcs.Bytes(v.PzlUnits[i]));
        }
    }

    private JObject Retouched(string pointer, JNode value)
    {
        // a tampered document written as a new archive file, its reference re-hashed (A05: "Gate·Reason 변경 후 Raw SHA 재계산")
        var doc = (JObject)JEditT.Set(w.DominanceDocument, pointer, value);
        var name = $"tampered-{Guid.NewGuid():N}.json";
        return EvidenceWriter.WriteDocument(w.Archive, doc, "DOMINANCE_RESULT", name);
    }

    [Fact]
    public void A05_A06_a_changed_reason_or_technical_value_is_found_by_the_re_execution()
    {
        Assert.Equal(EvidenceCodes.EvaluationMismatch, Refused(() => Verifier.VerifyFamily(w.DominanceRequest(reference: Retouched("/aggregate_evaluation/gate/reason", J.S("위조된 이유"))))).Code);
        Assert.Equal(EvidenceCodes.ReplayMismatch, Refused(() => Verifier.VerifyFamily(w.DominanceRequest(reference: Retouched("/units/0/technical/games/0/event_hash", J.S(new string('9', 64)))))).Code);
    }

    [Fact]
    public void A03_N15_N19_a_changed_pin_or_a_missing_authorization_is_refused_before_any_game()
    {
        // A03: the record's pin for one cell changed → AMPV refuses (the real file no longer meets the pin)
        var path = Schema.Text(w.Approval.Units("fc3-dom")[0]["seed_manifest_path"]);
        var changed = (JObject)JEditT.Set(w.Approval.Record, "/families/2/units/0/seed_manifest_sha256", J.S(new string('3', 64)));
        var a = new ApprovalRecordV1(changed, Jcs.Bytes(changed), Archive.Sha(Jcs.Bytes(changed)));
        Assert.Equal(EvidenceCodes.ApprovalMismatch, Refused(() => Verifier.VerifyFamily(w.DominanceRequest(approval: a))).Code);
        Assert.NotEmpty(path);
        // N15 / N19: a valid record without an execution authorization for the family
        Assert.Equal(EvidenceCodes.AuthorizationMissing, Refused(() => Verifier.Authority(w.Approval, null, "fc3-dom", false, true)).Code);
        var calOnly = (JObject)JEditT.Set(w.Authorization, "/families", J.A(J.S("fc3-cal")));
        Assert.Equal(EvidenceCodes.AuthorizationMissing, Refused(() => Verifier.Authority(w.Approval, calOnly, "fc3-dom", false, true)).Code);
    }

    [Fact]
    public void R01_only_official_not_ready_and_the_test_only_misuse_become_authorization_errors()
    {
        Assert.Equal(EvidenceCodes.AuthorizationMissing, Verifier.Wrap(new("Official.not_ready", "x"), "fc3-dom", false).Code);
        Assert.Equal(EvidenceCodes.AuthorizationMissing, Verifier.Wrap(new("Trust.test_only_flag_misuse", "x"), "fc3-dom", false).Code);   // N22
        var seed = Verifier.Wrap(new("Seed.file_hash_mismatch", "x"), "fc3-dom", false);
        Assert.Equal((EvidenceCodes.ApprovalMismatch, "Seed.file_hash_mismatch"), (seed.Code, seed.Cause));                                // N19-a: cause kept, not an authorization error
        Assert.Equal("Replay.run_result_hash_mismatch", Verifier.Wrap(new("Replay.run_result_hash_mismatch", "x"), "fc3-dom", true).Cause);

        // N22 (R01-B): a TEST_ONLY replay given a ready instance is refused at the gate
        var ready = ApprovalFormats.ToOfficialApprovals(w.Approval, executionPathReady: true);
        var o = DominanceOfficialReplay.Verify(w.DominanceResultDirectory, ready, w.Root, default, null, ReplayAuthority.TestOnlyVerification(["fc3-dom"]));
        Assert.Equal(("Trust.test_only_flag_misuse", false), (o.Error!.Value.Code, o.GamesExecuted));
        // the default authority with the not-ready instance stays Official.not_ready (current behaviour)
        Assert.Equal("Official.not_ready", DominanceOfficialReplay.Verify(w.DominanceResultDirectory, ApprovalFormats.ToOfficialApprovals(w.Approval), w.Root).Error!.Value.Code);
    }

    private JObject Receipt(VerifiedFamily v, string id) => J.O(
        ("format", J.S(Receipts.Format)), ("receipt_id", J.S(id)), ("validation_set_id", J.S(w.Approval.ValidationSetId)), ("approvals", w.Context.Approvals()),
        ("contracts", w.Approval.Record["contracts"]),
        ("verifier", J.O(("id", J.S("evidence-verifier")), ("version", J.S("1.0.0-test")), ("source_git_sha", J.S(w.Approval.GitCommitSha)), ("binary_sha256", J.S(Hashing.Sha256("verifier"))))),
        ("build_provenance", w.Approval.Ref("build_provenance")), ("environment_profile", w.Approval.Ref("environment_profile")), ("pzl_test_profile", w.Approval.Ref("pzl_test_profile")),
        ("execution_authorization_id", w.Authorization["authorization_id"]), ("test_only", J.B(v.TestOnly)), ("verification_decision", J.S("ELIGIBLE")),
        ("pzl_status", J.S("REQUIRED_CHECKS_SATISFIED")),
        ("targets", J.A(J.O(("kind", J.S("DOMINANCE")), ("run_id", J.S("run-dom-test")), ("evidence_id", ((JObject)v.Document["execution"])["evidence_id"]),
            ("evidence_hash", J.S(v.Payload.Hash)), ("technical_status", J.S(v.TechnicalStatus!)), ("statistical_status", J.S(v.StatisticalStatus!))))),
        ("checks", J.A()), ("source_files", J.A(v.SourceFiles)), ("child_receipt_ids", J.A()));

    [Fact]
    public void A_receipt_registers_once_idempotently_conflicts_on_other_bytes_and_a_local_registry_never_certifies()
    {
        // registry mechanics on a FIXTURE receipt: the verified payload and source files, with a fixture statistical state (this world's real gate is NOT_EVALUATED and gets no receipt)
        var v = Verifier.VerifyFamily(w.DominanceRequest()) with { TechnicalStatus = "COMPLETED", StatisticalStatus = "FAIL" };
        var db = Path.Combine(w.Root, "registry-" + Guid.NewGuid().ToString("N") + ".db");
        using var registry = new SqliteRegistry(db, RegistryRole.VerifierService, "S-1-5-21-1-2-3-1003");
        var id = Guid.NewGuid().ToString("D");
        var receipt = Receipt(v, id);
        var issued = Receipts.Issue(receipt, w.Archive, registry, () => null);
        Assert.Equal(ReceiptState.TestOnlyRegistered, issued.State);                      // A17: a local registry is never a trusted one
        Assert.Equal(issued.Sequence, Receipts.Issue(receipt, w.Archive, registry, () => null).Sequence);   // A15: retry after a lost response, same id and bytes
        var other = (JObject)JEditT.Set(receipt, "/source_files", J.A());
        Assert.Equal(EvidenceCodes.RegistrationConflict, Refused(() => Receipts.Issue(other, w.Archive, registry, () => null)).Code);   // A16 (file differs first)
        Assert.Equal(EvidenceCodes.EnvironmentMismatch, Refused(() => Receipts.Issue(Receipt(v, Guid.NewGuid().ToString("D")), w.Archive, registry, () => "C2 ≠ C0")).Code);   // N30 / E2-7
        Assert.Throws<Microsoft.Data.Sqlite.SqliteException>(() => registry.Execute("UPDATE registry_entry SET entry_id = 'x'"));   // immutable
        Assert.Throws<Microsoft.Data.Sqlite.SqliteException>(() => registry.Execute("DELETE FROM registry_entry"));
    }
}

/// <summary>T09 registry rules without a world: roles, closed requests, scope uniqueness, framing, pipe descriptor rules and the MINOR-01 AccessCheck matrix.</summary>
public sealed class RegistryTests : IDisposable
{
    private readonly string _db = Path.Combine(Path.GetTempPath(), "simharness-tests", "registry-" + Guid.NewGuid().ToString("N") + ".db");

    public RegistryTests() => Directory.CreateDirectory(Path.GetDirectoryName(_db)!);

    public void Dispose() => Microsoft.Data.Sqlite.SqliteConnection.ClearAllPools();

    private static byte[] ApprovalBytes(string id = "apr-test-1", string vs = "vs-test-1") =>
        Jcs.Bytes(JEditT.Set(JEditT.Set(SimHarness.Tests.Evidence.ApprovalFixture.Approval(), "/approval_record_id", J.S(id)), "/validation_set_id", J.S(vs)));

    [Fact]
    public void Owner_registers_approval_records_insert_or_compare_and_one_record_per_validation_set()
    {
        using var owner = new SqliteRegistry(_db, RegistryRole.Owner, "S-1-5-21-1-2-3-1002");
        Assert.Equal(RegisterOutcome.Inserted, owner.Register("APPROVAL_RECORD", "apr-test-1", ApprovalBytes()).Outcome);
        Assert.Equal(RegisterOutcome.AlreadyRegistered, owner.Register("APPROVAL_RECORD", "apr-test-1", ApprovalBytes()).Outcome);
        Assert.Equal("S-1-5-21-1-2-3-1002", owner.Get("APPROVAL_RECORD", "apr-test-1")!.RegistrantPrincipalId);
        Assert.Equal("Registry.scope_conflict", Assert.Throws<EvidenceException>(() => owner.Register("APPROVAL_RECORD", "apr-test-2", ApprovalBytes("apr-test-2"))).Error.Cause);
        Assert.Equal("Registry.id_mismatch", Assert.Throws<EvidenceException>(() => owner.Register("APPROVAL_RECORD", "apr-other", ApprovalBytes())).Error.Cause);
        Assert.Single(owner.GetByScope("APPROVAL_RECORD", "vs-test-1"));
        Assert.Null(owner.Get("APPROVAL_RECORD", "nope"));
    }

    [Fact]
    public void A_reader_and_an_unauthorized_caller_are_refused_before_any_transaction_and_requests_are_closed()
    {
        using (var owner = new SqliteRegistry(_db, RegistryRole.Owner, "S-1-5-21-1-2-3-1002"))
            owner.Register("APPROVAL_RECORD", "apr-test-1", ApprovalBytes());
        using var reader = new SqliteRegistry(_db, RegistryRole.EvidenceReader, "S-1-5-21-1-2-3-1004");
        Assert.NotNull(reader.Get("APPROVAL_RECORD", "apr-test-1"));                          // AT-14a/b: a reader may read
        foreach (var kind in RegistryKinds.All)                                              // AT-14q: every kind refused, no row changes
            Assert.Equal(EvidenceCodes.RegistrationUnauthorized, Assert.Throws<EvidenceException>(() => reader.Register(kind, "x", [1])).Error.Code);
        Assert.Single(reader.GetByScope("APPROVAL_RECORD", "vs-test-1"));
        using var verifier = new SqliteRegistry(_db, RegistryRole.VerifierService, "S-1-5-21-1-2-3-1003");
        Assert.Equal(EvidenceCodes.RegistrationUnauthorized, Assert.Throws<EvidenceException>(() => verifier.Register("APPROVAL_RECORD", "apr-test-9", ApprovalBytes("apr-test-9", "vs-9"))).Error.Code);
        using var stranger = new SqliteRegistry(_db, RegistryRole.Unauthorized, "S-1-5-21-9-9-9-9");
        Assert.Throws<EvidenceException>(() => stranger.Get("APPROVAL_RECORD", "apr-test-1"));

        // AT-14e / N27-c: a request naming a role or a registrant is a schema error; the response of the service carries the error, never a role change
        var forged = Jcs.Bytes(J.O(("op", J.S("get")), ("entry_kind", J.S("APPROVAL_RECORD")), ("entry_id", J.S("apr-test-1")), ("role", J.S("OWNER"))));
        Assert.Equal("Evidence.schema_invalid", Schema.Text(RegistryRequests.Handle(reader, RegistryRole.EvidenceReader, forged)["code"]));
        var register = Jcs.Bytes(J.O(("op", J.S("register")), ("entry_kind", J.S("VERIFICATION_RECEIPT")), ("entry_id", J.S("x")), ("raw_bytes_base64", J.S(Convert.ToBase64String([1])))));
        Assert.Equal("Evidence.registration_unauthorized", Schema.Text(RegistryRequests.Handle(reader, RegistryRole.EvidenceReader, register)["code"]));
        var get = Jcs.Bytes(J.O(("op", J.S("get")), ("entry_kind", J.S("APPROVAL_RECORD")), ("entry_id", J.S("apr-test-1"))));
        Assert.Equal("FOUND", Schema.Text(RegistryRequests.Handle(reader, RegistryRole.EvidenceReader, get)["status"]));
    }

    /// <summary>OWNER decision 3: the one added operation is read-only, closed and answers the store's instance id to every authenticated role; the other three keep their meaning.</summary>
    [Fact]
    public void The_registry_identity_request_is_closed_read_only_and_open_to_every_authenticated_role()
    {
        var identity = Jcs.Bytes(J.O(("op", J.S(RegistryRequests.IdentityOp))));
        foreach (var role in new[] { RegistryRole.Owner, RegistryRole.VerifierService, RegistryRole.EvidenceReader })
        {
            using var store = new SqliteRegistry(_db, role, "S-1-5-21-1-2-3-1003", "registry-test-1");
            var reply = RegistryRequests.Handle(store, role, identity);
            Assert.Equal(J.O(("status", J.S("FOUND")), ("registry_instance_id", J.S("registry-test-1"))).Members.Select(m => (m.Key, Jcs.Text(m.Value))), reply.Members.Select(m => (m.Key, Jcs.Text(m.Value))));
        }

        using var stranger = new SqliteRegistry(_db, RegistryRole.Unauthorized, "S-1-5-21-9-9-9-9", "registry-test-1");
        Assert.Equal("Registry.unauthorized", Schema.Text(RegistryRequests.Handle(stranger, RegistryRole.Unauthorized, identity)["cause"]));
        using var reader = new SqliteRegistry(_db, RegistryRole.EvidenceReader, "S-1-5-21-1-2-3-1004", "registry-test-1");
        foreach (var extra in new[] { ("entry_kind", J.S("APPROVAL_RECORD")), ("registry_instance_id", J.S("registry-test-1")), ("role", J.S("OWNER")) })   // closed: no other member
            Assert.Equal("Evidence.schema_invalid", Schema.Text(RegistryRequests.Handle(reader, RegistryRole.EvidenceReader, Jcs.Bytes(J.O(("op", J.S(RegistryRequests.IdentityOp)), extra)))["code"]));
        Assert.Equal("Evidence.schema_invalid", Schema.Text(RegistryRequests.Handle(reader, RegistryRole.EvidenceReader, Jcs.Bytes(J.O(("op", J.S("get_identity")))))["code"]));   // no other new op
        Assert.Empty(reader.GetByScope("APPROVAL_RECORD", "vs-none"));                                     // nothing was written by any identity request
    }

    [Fact]
    public void Frames_are_length_prefixed_and_bounded()
    {
        var body = Jcs.Bytes(J.O(("op", J.S("get"))));
